class ProductOfNumbers {
public:
    vector<int> nums;
    ProductOfNumbers() {
        
    }
    
    void add(int num) {
        nums.push_back(num);
    }
    
    int getProduct(int k) {
        int ans = 1 , n = nums.size();
        for(int i = n - 1 ; i >= n-k ; i--){
            ans *= nums[i];
            if(ans == 0)    return 0;
        }
        return ans;
    }
};

